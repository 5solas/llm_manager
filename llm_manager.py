def _plain_mcp(cat: dict) -> dict:
    out = {}
    for name, s in cat["mcp"].items():
        if s["command"]:
            out[name] = {"command": s["command"], "args": s["args"]}
            if s["env"]:
                out[name]["env"] = s["env"]
        else:
            out[name] = {"url": s["url"]}
            if s["headers"]:
                out[name]["headers"] = s["headers"]
    return out


def render_hermes(cat: dict, skills_dir: str) -> tuple[dict, list[str]]:
    """Returns (config patch, notes). Models under hermes' minimum context are left out."""
    notes = []
    providers = {}
    for name, ep in cat["endpoints"].items():
        models = {}
        for mid, m in cat["models"].items():
            if m["endpoint"] != name:
                continue
            if m["context"] < HERMES_MIN_CONTEXT:
                notes.append(f"hermes: skipped '{mid}' (context {m['context']} is under {HERMES_MIN_CONTEXT})")
                continue
            models[mid] = {"context_length": m["context"]}
        providers[name] = {"base_url": ep["root"] + "/v1", "key_env": ep["key_env"], "models": models}
    default = cat["default"]
    cfg: dict = {
        "model": {"default": default, "provider": "custom:" + cat["models"][default]["endpoint"]},
        "providers": providers,
        # keep every helper task on the in-house endpoint (vision would otherwise fall through to OpenRouter etc.)
        "auxiliary": {task: {"provider": "main"} for task in HERMES_AUX_TASKS},
        "auth": {"adopt_external_logins": False},
        "approvals": {"mode": "off" if cat["policy"]["approvals"] == "off" else "manual"},
        "skills": {"external_dirs": [skills_dir]},
    }
    if not cat["policy"]["auto_update"]:
        cfg["updates"] = {"check": False}
    if not cat["policy"]["external_web"]:
        cfg["web"] = {"keyless_fallback": False}
        cfg["agent"] = {"disabled_toolsets": ["web", "browser"]}
    if cat["mcp"]:
        cfg["mcp_servers"] = _plain_mcp(cat)
    return deep_merge(cfg, cat["extra"]["hermes"]), notes


def claude_key_helper_needed(cat: dict) -> bool:
    """Claude Code reads only ANTHROPIC_* key variables itself; any other name goes through apiKeyHelper."""
    cc = cat["claude_code"]
    return bool(cc["model"]) and cc["key_env"] not in CLAUDE_NATIVE_KEYS


def render_claude_settings(cat: dict, statusline_path: str,
                           key_helper_path: str = "api-key.ps1") -> tuple[dict, list[str]]:
    notes = []
    cc = cat["claude_code"]
    env: dict = {}
    if cc["model"]:
        env["ANTHROPIC_BASE_URL"] = cat["endpoints"][cc["endpoint"]]["root"]
        env["ANTHROPIC_MODEL"] = cc["model"]
        for slot in ("opus", "sonnet", "haiku"):
            if cc[slot]:
                env[f"ANTHROPIC_DEFAULT_{slot.upper()}_MODEL"] = cc[slot]
    else:
        notes.append("claude_code: no Claude-family model in the catalog, so the gateway settings were left out")
    if not cat["policy"]["telemetry"]:
        env["CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC"] = "1"
    if not cat["policy"]["auto_update"]:
        env["DISABLE_AUTOUPDATER"] = "1"
    cfg: dict = {
        "env": env,
        "permissions": {"defaultMode": "bypassPermissions" if cat["policy"]["approvals"] == "off" else "default"},
        "statusLine": {
            "type": "command",
            "command": f'powershell -NoProfile -ExecutionPolicy Bypass -File "{statusline_path}"',
        },
    }
    if not cat["policy"]["external_web"]:
        cfg["permissions"]["deny"] = ["WebFetch", "WebSearch"]
    if claude_key_helper_needed(cat):
        # the documented Windows form; Claude Code runs it through cmd and sends the output as the key
        cfg["apiKeyHelper"] = (f'powershell -NoProfile -ExecutionPolicy Bypass -File "{key_helper_path}" '
                               f'{cc["key_env"]}')
    return deep_merge(cfg, cat["extra"]["claude_code"]), notes


def claude_mcp_commands(cat: dict) -> list[list[str]]:
    cmds = []
    for name, s in cat["mcp"].items():
        if s["command"]:
            spec = {"type": "stdio", "command": s["command"], "args": s["args"], "env": s["env"]}
        else:
            spec = {"type": "http", "url": s["url"], "headers": s["headers"]}
        cmds.append(["claude", "mcp", "add-json", name, json.dumps(spec), "--scope", "user"])
    return cmds


# --------------------------------------------------------------------------- merge helpers

def deep_merge(base: dict, patch: dict, replace=(), union=(), _path=()) -> dict:
    """Merge patch into base. Paths in `replace` are overwritten whole; lists at `union` paths are unioned."""
    out = dict(base)
    for key, value in patch.items():
        path = _path + (key,)
        if key not in out or path in replace:
            out[key] = copy.deepcopy(value)
        elif isinstance(value, dict) and isinstance(out[key], dict):
            out[key] = deep_merge(out[key], value, replace, union, path)
        elif path in union and isinstance(value, list) and isinstance(out[key], list):
            out[key] = out[key] + [x for x in value if x not in out[key]]
        else:
            out[key] = copy.deepcopy(value)
    return out


def strip_jsonc(text: str) -> str:
    """Remove // and /* */ comments and trailing commas, leaving string contents alone."""
    out, i, n = [], 0, len(text)
    while i < n:
        ch = text[i]
        if ch == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = n if end < 0 else end + 2
        else:
            out.append(ch)
            i += 1
    return re.sub(r",(\s*[}\]])", r"\1", "".join(out))


def replace_block(existing: str, body: str) -> str:
    block = f"{BLOCK_BEGIN}\n{body.rstrip()}\n{BLOCK_END}"
    if BLOCK_BEGIN in existing and BLOCK_END in existing:
        start = existing.index(BLOCK_BEGIN)
        end = existing.index(BLOCK_END) + len(BLOCK_END)
        return existing[:start] + block + existing[end:]
    if existing.strip():
        return existing.rstrip("\n") + "\n\n" + block + "\n"
    return block + "\n"


def dump_json(data) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


# --------------------------------------------------------------------------- file plan

@dataclass
class FileOp:
    rel: str                 # path under out/
    target: Path             # where it is installed
    kind: str                # json | jsonc | merge_json | merge_yaml | block | text | copy
    data: object = None
    replace: tuple = ()
    union: tuple = ()
    source: Path | None = None

    def fragment(self) -> bytes:
        """What is written to out/ for review (the patch, for merged files)."""
        if self.kind == "copy":
            return self.source.read_bytes()
        if self.kind in ("json", "merge_json"):
            return dump_json(self.data).encode()
        if self.kind == "jsonc":
            return (f"// {GENERATED_NOTE}\n" + dump_json(self.data)).encode()
        if self.kind == "merge_yaml":
            return yaml.safe_dump(self.data, sort_keys=False, allow_unicode=True).encode()
        return str(self.data).encode()

    def final(self) -> bytes:
        """Content the target will have after apply (merges read the existing target)."""
        if self.kind == "merge_json":
            existing = {}
            if self.target.exists():
                existing = json.loads(strip_jsonc(self.target.read_text(encoding="utf-8")) or "{}")
            return dump_json(deep_merge(existing, self.data, self.replace, self.union)).encode()
        if self.kind == "merge_yaml":
            existing = {}
            if self.target.exists():
                existing = yaml.safe_load(self.target.read_text(encoding="utf-8")) or {}
            merged = deep_merge(existing, self.data, self.replace, self.union)
            return yaml.safe_dump(merged, sort_keys=False, allow_unicode=True).encode()
        if self.kind == "block":
            existing = self.target.read_text(encoding="utf-8") if self.target.exists() else ""
            return replace_block(existing, str(self.data)).encode()
        return self.fragment()


def tool_dirs(home: Path | None) -> dict:
    explicit = home is not None
    h = Path(home) if explicit else Path.home()
    if explicit:
        hermes = h / "AppData" / "Local" / "hermes" if os.name == "nt" else h / ".hermes"
    elif os.environ.get("HERMES_HOME"):
        hermes = Path(os.environ["HERMES_HOME"])
