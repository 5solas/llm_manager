def cmd_diff(cat: dict, home: Path | None) -> int:
    ops, _ = plan_files(cat, home)
    changed = 0
    for op in ops:
        new = op.final()
        old = op.target.read_bytes() if op.target.exists() else None
        if old == new:
            continue
        changed += 1
        print(f"=== {op.target} ({'new' if old is None else 'changed'})")
        try:
            a = (old or b"").decode("utf-8").splitlines()
            b = new.decode("utf-8").splitlines()
        except UnicodeDecodeError:
            print("(binary file)")
            continue
        for line in difflib.unified_diff(a, b, "current", "after apply", lineterm=""):
            print(line)
    print(f"{changed} of {len(ops)} files would change")
    return changed


def cmd_apply(cat: dict, home: Path | None, backups: Path, set_env: bool) -> list[Path]:
    ops, notes = plan_files(cat, home)
    dirs = tool_dirs(home)
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    written = []
    for op in ops:
        new = op.final()
        if op.target.exists():
            if op.target.read_bytes() == new:
                continue
            try:
                rel = op.target.relative_to(dirs["home"])
            except ValueError:
                rel = Path(*op.target.parts[1:])
            backup = backups / stamp / rel
            backup.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(op.target, backup)
        op.target.parent.mkdir(parents=True, exist_ok=True)
        op.target.write_bytes(new)
        written.append(op.target)
        print("wrote", op.target)
    saved = (backups / stamp).exists()
    print(f"{len(written)} of {len(ops)} files written" + (f"; originals saved in {backups / stamp}" if saved else ""))
    for note in notes:
        print("note:", note)
    if set_env:
        apply_env(cat)
    else:
        user, _ = env_plan(cat)
        if user:
            print("environment variables not set (re-run with --env): " + ", ".join(sorted(user)))
    print("\n".join(key_instructions(cat)))
    return written


def run(cmd: list[str], timeout: int = 60, input: str | None = None,
        cwd: str | None = None) -> tuple[int | None, str]:
    """Run a command (in cwd, when given); input, when given, is passed on stdin (otherwise stdin is empty)."""
    exe = shutil.which(cmd[0])
    if not exe:
        return None, f"{cmd[0]} not found on PATH"
    stdin = {"stdin": subprocess.DEVNULL} if input is None else {"input": input}
    try:
        p = subprocess.run([exe, *cmd[1:]], capture_output=True, text=True, timeout=timeout,
                           encoding="utf-8", errors="replace", cwd=cwd, **stdin)
        return p.returncode, (p.stdout + p.stderr).strip()
    except subprocess.TimeoutExpired:
        return None, "timed out"
    except OSError as exc:
        return None, str(exc)


