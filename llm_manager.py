def render_opencode(cat: dict) -> dict:
    providers = {}
    for name, ep in cat["endpoints"].items():
        ep_api = ep["api"]
        ep_auth = ep["auth"]
        uses_api_key = ep_auth == "bearer" or (ep_api == "anthropic-messages" and ep_auth == "x-api-key")
        settings: dict = {"baseURL": endpoint_api_url(ep)}
        if uses_api_key:
            settings["apiKey"] = "{env:%s}" % ep["key_env"]
        elif ep_api != "openai-completions":
            # Only @opencode/ai/providers/openai-compatible allows omitting apiKey.
            settings["apiKey"] = "unused"

        headers = dict(ep["headers"])
        if ep_auth in ("api-key", "x-api-key") and not (ep_api == "anthropic-messages" and ep_auth == "x-api-key"):
            headers[ep_auth] = "{env:%s}" % ep["key_env"]

        models = {}
        for mid, m in cat["models"].items():
            if m["endpoint"] != name:
                continue
            m_entry: dict = {
                "name": mid,
                "limit": {"context": m["context"], "output": m["max_output"]},
                "capabilities": {
                    "tools": m["tools"],
                    "input": ["text", "image"] if m["vision"] else ["text"],
                    "output": ["text"],
                },
            }
            m_api = m.get("api")
            if m_api and m_api != ep_api:
                m_entry["package"] = OPENCODE_PACKAGES[m_api]
                if "apiKey" not in settings and m_api != "openai-completions":
                    m_entry["settings"] = {"apiKey": "unused"}
            models[mid] = m_entry

        p_entry: dict = {
            "name": name,
            "package": OPENCODE_PACKAGES[ep_api],
            "settings": settings,
            "models": models,
        }
        if headers:
            p_entry["headers"] = headers
        if ep.get("kind") in ("vllm", "ollama"):
            p_entry["compatibility"] = {"developerRole": False}
        providers[name] = p_entry
    # experimental.policies works on 2.0.26 and on 2.3 (top-level policies is ignored before 2.0.29)
    policies = [{"action": "provider.use", "resource": "*", "effect": "deny"}]
    policies += [{"action": "provider.use", "resource": n, "effect": "allow"} for n in cat["endpoints"]]
    cfg: dict = {
        "$schema": OPENCODE_SCHEMA,
        "model": model_ref(cat, cat["default"]),
        "providers": providers,
        "agents": {"title": {"model": model_ref(cat, cat["tiers"]["tier3"][0])}},
        "experimental": {"policies": policies},
    }
    if not cat["policy"]["auto_update"]:
        cfg["update"] = "disable"
    permissions = []
    if cat["policy"]["approvals"] == "ask":
        permissions += [{"action": a, "resource": "*", "effect": "ask"} for a in ("shell", "edit")]
    if not cat["policy"]["external_web"]:
        permissions += [{"action": a, "resource": "*", "effect": "deny"} for a in ("webfetch", "websearch")]
    if permissions:
        cfg["permissions"] = permissions
    servers = {}
    for name, s in cat["mcp"].items():
        if s["command"]:
            servers[name] = {"type": "local", "command": [s["command"], *s["args"]]}
            if s["env"]:
                servers[name]["environment"] = s["env"]
        else:
            servers[name] = {"type": "remote", "url": s["url"]}
            if s["headers"]:
                servers[name]["headers"] = s["headers"]
    if servers:
        cfg["mcp"] = {"servers": servers}
    return deep_merge(cfg, cat["extra"]["opencode"])


def render_omo_config(cat: dict) -> dict:
    def chain(spec):
        out = []
        for mid in cat["tiers"][spec["tier"]]:
            ref = model_ref(cat, mid)
            if cat["models"][mid]["reasoning"] and spec.get("reasoning"):
                out.append({"model": ref, "reasoning": spec["reasoning"]})
            else:
                out.append(ref)
        return out

    roles = cat["omo_roles"]
    task: dict = {"default_concurrency": roles["concurrency"]}
    p_conc = {n: ep["concurrency"] for n, ep in cat["endpoints"].items() if ep.get("concurrency") is not None}
    if p_conc:
        task["provider_concurrency"] = p_conc
    cfg: dict = {
        "$schema": OMO_SCHEMA,
        # pins the main model for headless (-p) and desktop runs; the terminal UI uses settings.json
        "model_profile": model_ref(cat, cat["default"]),
        "agents": {n: {"models": chain(s)} for n, s in roles["agents"].items()},
        "categories": {n: {"models": chain(s)} for n, s in roles["categories"].items()},
        "task": task,
    }
    if "quick" in roles["categories"]:
        cfg["memory"] = {"recall": {"category": "quick"}}
    if not cat["policy"]["telemetry"]:
        cfg["telemetry"] = {"enabled": False}
        cfg["device_service"] = {"enabled": False}
    return deep_merge(cfg, cat["extra"]["omo"])


def render_omo_models(cat: dict) -> dict:
    providers = {}
    for name, ep in cat["endpoints"].items():
        ep_api = ep["api"]
        ep_auth = ep["auth"]
        base_url = anthropic_base_url(ep) if ep_api == "anthropic-messages" else endpoint_api_url(ep)
        p_entry: dict = {
            "name": name,
            "baseUrl": base_url,
        }
        headers = dict(ep["headers"])
        if ep_auth == "bearer":
            p_entry["apiKey"] = "$" + ep["key_env"]
            if ep_api == "anthropic-messages":
                p_entry["authHeader"] = True
        elif ep_auth == "x-api-key" and ep_api == "anthropic-messages":
            p_entry["apiKey"] = "$" + ep["key_env"]
        elif ep_auth in ("api-key", "x-api-key"):
            headers[ep_auth] = "$" + ep["key_env"]
        elif ep_auth == "none":
            p_entry["apiKey"] = "none"
        p_entry["api"] = ep_api
        if headers:
            p_entry["headers"] = headers
        if ep.get("kind") in ("vllm", "ollama"):
            p_entry["compat"] = {"supportsDeveloperRole": False}

        models_list = []
        for mid, m in cat["models"].items():
            if m["endpoint"] != name:
                continue
            m_entry: dict = {
                "id": mid,
                "name": mid,
                "reasoning": m["reasoning"],
                "input": ["text", "image"] if m["vision"] else ["text"],
                "contextWindow": m["context"],
                "maxTokens": m["max_output"],
            }
            m_api = m.get("api")
            if m_api and m_api != ep_api:
                m_entry["api"] = m_api
                m_base = anthropic_base_url(ep) if m_api == "anthropic-messages" else endpoint_api_url(ep)
                if m_base != base_url:
                    m_entry["baseUrl"] = m_base
            models_list.append(m_entry)
        p_entry["models"] = models_list
        providers[name] = p_entry
    return {"providers": providers}


def render_omo_settings(cat: dict) -> dict:
    default = cat["default"]
    return {
        "defaultProvider": cat["models"][default]["endpoint"],
        "defaultModel": default,
        "permissionPreset": "full-access" if cat["policy"]["approvals"] == "off" else "ask",
        "skills": ["~/.claude/skills"],
    }


def render_omo_mcp(cat: dict) -> dict:
    servers: dict = {}
    if not cat["policy"]["external_web"]:
        servers["context7"] = {"enabled": False}
        servers["grep_app"] = {"enabled": False}
    servers.update(_plain_mcp(cat))
    return {"mcpServers": servers}


def _plain_mcp(cat: dict) -> dict:
    out = {}
    for name, s in cat["mcp"].items():
        if s["command"]:
            out[name] = {"command": s["command"], "args": s["args"]}
            if s["env"]:
                out[name]["env"] = s["env"]
        else:
            out[name] = {"url": s["url"]}
            if s["headers"]:
                out[name]["headers"] = s["headers"]
    return out


def render_hermes(cat: dict, skills_dir: str) -> tuple[dict, list[str]]:
    """Returns (config patch, notes). Models under hermes' minimum context are left out."""
    notes = []
    providers = {}
    for name, ep in cat["endpoints"].items():
        ep_api = ep["api"]
        ep_auth = ep["auth"]
        models = {}
        for mid, m in cat["models"].items():
            if m["endpoint"] != name:
                continue
            if m["context"] < HERMES_MIN_CONTEXT:
                notes.append(f"hermes: skipped '{mid}' (context {m['context']} is under {HERMES_MIN_CONTEXT})")
                continue
            m_entry: dict = {"context_length": m["context"]}
            if m["vision"]:
                m_entry["supports_vision"] = True
            models[mid] = m_entry

        p_entry: dict = {"base_url": endpoint_api_url(ep)}
        headers = dict(ep["headers"])
        if ep_auth == "bearer" or (ep_auth == "x-api-key" and ep_api == "anthropic-messages"):
            p_entry["key_env"] = ep["key_env"]
        elif ep_auth in ("api-key", "x-api-key"):
            p_entry["api_key"] = "no-key-required"
            headers[ep_auth] = "${%s}" % ep["key_env"]
        else:
            p_entry["api_key"] = "no-key-required"
        if ep_api != "openai-completions":
            p_entry["transport"] = HERMES_TRANSPORTS[ep_api]
        if headers:
            p_entry["extra_headers"] = headers
        p_entry["models"] = models
        providers[name] = p_entry

    default = cat["default"]
    eligible = [m for m, info in cat["models"].items() if info["context"] >= HERMES_MIN_CONTEXT]
    tier_order = [m for t in TIERS for m in cat["tiers"][t] if m in eligible]
    vision_candidates = [default, *tier_order, *eligible]
    vision_mid = next((m for m in vision_candidates if m in eligible and cat["models"][m]["vision"]), default)
    fast_candidates = [
        *(m for m in cat["tiers"]["tier3"] if m in eligible),
        *(m for m in cat["tiers"]["tier2"] if m in eligible),
        *(m for m in cat["tiers"]["tier1"] if m in eligible),
        default,
    ]
    fast_mid = fast_candidates[0]
    auxiliary = {}
    for task in HERMES_AUX_TASKS:
        chosen_mid = vision_mid if task == "vision" else fast_mid
        auxiliary[task] = {
            "provider": "custom:" + cat["models"][chosen_mid]["endpoint"],
            "model": chosen_mid,
        }

    default_tier = next((t for t in TIERS if default in cat["tiers"][t]), None)
    fallback_providers = []
    if default_tier:
        for mid in cat["tiers"][default_tier]:
            if mid != default and mid in eligible:
                fallback_providers.append({
                    "provider": "custom:" + cat["models"][mid]["endpoint"],
                    "model": mid,
                })

    cfg: dict = {
        "model": {"default": default, "provider": "custom:" + cat["models"][default]["endpoint"]},
        "providers": providers,
        "fallback_providers": fallback_providers,
        # pin helper tasks to explicit custom:<endpoint> + model (provider: main normalizes to bare 'custom')
        "auxiliary": auxiliary,
        "auth": {"adopt_external_logins": False},
        "approvals": {"mode": "off" if cat["policy"]["approvals"] == "off" else "manual"},
        "skills": {"external_dirs": [skills_dir]},
    }
    if not cat["policy"]["auto_update"]:
        cfg["updates"] = {"check": False}
    if not cat["policy"]["external_web"]:
        cfg["web"] = {"keyless_fallback": False}
        cfg["agent"] = {"disabled_toolsets": ["web", "browser"]}
    if cat["mcp"]:
        cfg["mcp_servers"] = _plain_mcp(cat)
    return deep_merge(cfg, cat["extra"]["hermes"]), notes


