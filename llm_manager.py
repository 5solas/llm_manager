class CatalogError(Exception):
    def __init__(self, problems: list[str]):
        super().__init__("\n".join(problems))
        self.problems = problems


def guess_family(model_id: str) -> str:
    name = model_id.lower()
    if "claude" in name:
        return "claude"
    if "gemini" in name:
        return "gemini"
    if re.search(r"gpt|codex|(^|[/-])o[134]([-/]|$)", name):
        return "gpt"
    return "open"


def split_endpoint_url(url: str) -> tuple[str, str]:
    raw = str(url or "").strip().rstrip("/")
    if raw.endswith("/v1"):
        return raw[:-3], "/v1"
    return raw, "/v1"


def endpoint_root(url: str) -> str:
    return split_endpoint_url(url)[0]


def endpoint_api_url(ep: dict) -> str:
    return ep["root"] + ep["api_base"]


def normalize_catalog(raw: dict) -> dict:
    """Fill defaults and validate. Raises CatalogError listing every problem found."""
    raw = raw or {}
    problems: list[str] = []
    cat: dict = {}

    endpoints = {}
    for name, ep in (raw.get("endpoints") or {}).items():
        ep = ep or {}
        if not NAME_RE.match(str(name)):
            problems.append(f"endpoints.{name}: name may only use letters, digits, '-' and '_'")
        raw_url = str(ep.get("base_url") or "").strip().rstrip("/")
        if not raw_url.startswith(("http://", "https://")):
            problems.append(f"endpoints.{name}.base_url: must start with http:// or https://")
        auth = ep.get("auth") if ep.get("auth") is not None else "bearer"
        if auth not in AUTH_MODES:
            problems.append(f"endpoints.{name}.auth: must be one of {', '.join(AUTH_MODES)}")
        key_env = ep.get("key_env")
        if auth != "none" and not key_env:
            problems.append(f"endpoints.{name}.key_env: name of the environment variable holding the API key is required")
        if "api_base" in ep and ep["api_base"] is not None:
            raw_base = ep["api_base"]
            if not isinstance(raw_base, str) or (raw_base != "" and not raw_base.startswith("/")):
                problems.append(f"endpoints.{name}.api_base: must be '' or start with '/'")
                api_base = "/v1"
            else:
                api_base = raw_base.rstrip("/")
            root = raw_url[:-len(api_base)] if api_base and raw_url.endswith(api_base) else endpoint_root(raw_url)
        else:
            root, api_base = split_endpoint_url(raw_url)
        api = ep.get("api") or "openai-completions"
        if api not in API_FORMATS:
            problems.append(f"endpoints.{name}.api: must be one of {', '.join(API_FORMATS)}")
        kind = ep.get("kind")
        if kind is not None and not isinstance(kind, str):
            problems.append(f"endpoints.{name}.kind: must be a string")
            kind = None
        raw_headers = ep.get("headers")
        if raw_headers is not None and not isinstance(raw_headers, dict):
            problems.append(f"endpoints.{name}.headers: must be a mapping of header names to values")
            headers = {}
        else:
            headers = {str(k): str(v) for k, v in (raw_headers or {}).items()}
        concurrency = ep.get("concurrency")
        if concurrency is not None:
            if not isinstance(concurrency, int) or isinstance(concurrency, bool) or concurrency <= 0:
                problems.append(f"endpoints.{name}.concurrency: must be a positive integer")
                concurrency = None
        endpoints[str(name)] = {
            "root": root,
            "api_base": api_base,
            "auth": auth,
            "key_env": str(key_env) if key_env else None,
            "api": api,
            "kind": kind,
            "headers": headers,
            "concurrency": concurrency,
        }
    if not endpoints:
        problems.append("endpoints: at least one endpoint is required")
    cat["endpoints"] = endpoints

    defined_eps = ", ".join(endpoints)
    models = {}
    for mid, m in (raw.get("models") or {}).items():
        m = m or {}
        mid = str(mid)
        endpoint = m.get("endpoint") or (next(iter(endpoints)) if len(endpoints) == 1 else None)
        if endpoint not in endpoints:
            avail = f" (defined endpoints: {defined_eps})" if endpoints else ""
            problems.append(f"models.{mid}.endpoint: '{endpoint}' is not a defined endpoint{avail}")
        m_api = m.get("api")
        if m_api is not None and m_api not in API_FORMATS:
            problems.append(f"models.{mid}.api: must be one of {', '.join(API_FORMATS)}")
        context = m.get("context")
        if not isinstance(context, int) or isinstance(context, bool) or context <= 0:
            problems.append(f"models.{mid}.context: context window in tokens is required")
            context = 0
        models[mid] = {
            "endpoint": endpoint,
            "family": m.get("family") or guess_family(mid),
            "api": m_api,
            "context": context,
            "max_output": int(m.get("max_output") or 8192),
            "reasoning": bool(m.get("reasoning", False)),
            "tools": bool(m.get("tools", True)),
            "vision": bool(m.get("vision", False)),
        }
    if not models:
        problems.append("models: at least one model is required")
    cat["models"] = models

    tiers = {}
    for tier in TIERS:
        ids = [str(x) for x in ((raw.get("tiers") or {}).get(tier) or [])]
        if not ids:
            problems.append(f"tiers.{tier}: needs at least one model")
        for mid in ids:
            if mid not in models:
                problems.append(f"tiers.{tier}: '{mid}' is not in models")
        tiers[tier] = ids
    cat["tiers"] = tiers

    default = raw.get("default") or (tiers["tier2"][0] if tiers["tier2"] else None)
    if default not in models:
        problems.append(f"default: '{default}' is not in models")
    cat["default"] = default

    policy = dict(raw.get("policy") or {})
    approvals = policy.get("approvals", "off")
    if isinstance(approvals, bool):  # YAML reads a bare off/on as a boolean
        approvals = "ask" if approvals else "off"
    if approvals not in ("off", "ask"):
        problems.append("policy.approvals: must be 'off' or 'ask'")
    cat["policy"] = {
        "telemetry": bool(policy.get("telemetry", False)),
        "auto_update": bool(policy.get("auto_update", False)),
        "external_web": bool(policy.get("external_web", True)),
        "approvals": approvals,
    }

    tools = raw.get("tools") or {}
    cat["tools"] = {t: bool(tools.get(t, True)) for t in ("opencode", "omo", "hermes", "claude_code")}

    roles = {}
    user_roles = raw.get("omo_roles") or {}
    for group in ("agents", "categories"):
        merged = {**DEFAULT_OMO_ROLES[group], **(user_roles.get(group) or {})}
        roles[group] = {}
        for role, spec in merged.items():
            spec = {"tier": spec} if isinstance(spec, str) else dict(spec or {})
            if spec.get("tier") not in TIERS:
                problems.append(f"omo_roles.{group}.{role}: tier must be one of {', '.join(TIERS)}")
                continue
            spec.setdefault("reasoning", TIER_REASONING[spec["tier"]])
            roles[group][role] = spec
    roles["concurrency"] = int(user_roles.get("concurrency") or 4)
    cat["omo_roles"] = roles

    mcp = {}
    for name, server in (raw.get("mcp") or {}).items():
        server = server or {}
        if not NAME_RE.match(str(name)):
            problems.append(f"mcp.{name}: name may only use letters, digits, '-' and '_'")
        if bool(server.get("command")) == bool(server.get("url")):
            problems.append(f"mcp.{name}: set exactly one of 'command' or 'url'")
        mcp[str(name)] = {
            "command": server.get("command"),
            "args": [str(a) for a in (server.get("args") or [])],
            "env": {str(k): str(v) for k, v in (server.get("env") or {}).items()},
            "url": server.get("url"),
            "headers": {str(k): str(v) for k, v in (server.get("headers") or {}).items()},
        }
    cat["mcp"] = mcp

    cat["claude_code"] = _resolve_claude_code(raw.get("claude_code") or {}, cat, problems)

    if cat["tools"]["hermes"] and default in models and 0 < models[default]["context"] < HERMES_MIN_CONTEXT:
        problems.append(
            f"default: hermes rejects models under {HERMES_MIN_CONTEXT} tokens of context "
            f"('{default}' has {models[default]['context']}); pick another default or set tools.hermes: false"
        )

    extra = raw.get("extra") or {}
    cat["extra"] = {t: dict(extra.get(t) or {}) for t in cat["tools"]}

    if problems:
        raise CatalogError(problems)
    return cat


def _resolve_claude_code(spec: dict, cat: dict, problems: list[str]) -> dict:
    """Pick a single endpoint and Claude-family models for the opus/sonnet/haiku slots."""
    models, tiers, endpoints = cat["models"], cat["tiers"], cat["endpoints"]

    explicit_ep = spec.get("endpoint")
    if explicit_ep is not None and explicit_ep not in endpoints:
        problems.append(f"claude_code.endpoint: '{explicit_ep}' is not a defined endpoint")
        explicit_ep = None

    explicit_main = spec.get("model")
    for slot in ("model", "opus", "sonnet", "haiku"):
        mid = spec.get(slot)
        if mid is None:
            continue
        if mid not in models:
            problems.append(f"claude_code.{slot}: '{mid}' is not in models")
        elif models[mid]["family"] != "claude":
            problems.append(f"claude_code.{slot}: '{mid}' is not a Claude model; Claude Code supports only Claude models")

    target_ep = explicit_ep
    if not target_ep and explicit_main in models:
        target_ep = models[explicit_main]["endpoint"]
    if not target_ep:
        default = cat.get("default")
        if default in models and models[default]["family"] == "claude":
            target_ep = models[default]["endpoint"]
    if not target_ep:
        for tier in TIERS:
            found = next((m for m in tiers[tier] if models.get(m, {}).get("family") == "claude"), None)
            if found:
                target_ep = models[found]["endpoint"]
                break
    if not target_ep:
        found = next((m for m, info in models.items() if info["family"] == "claude"), None)
        if found:
            target_ep = models[found]["endpoint"]

    for slot in ("model", "opus", "sonnet", "haiku"):
        mid = spec.get(slot)
        if mid in models and target_ep and models[mid]["endpoint"] != target_ep:
            problems.append(
                f"claude_code.{slot}: '{mid}' is on endpoint '{models[mid]['endpoint']}', "
                f"but Claude Code is using endpoint '{target_ep}' (Claude Code supports only one endpoint)"
            )

    def first_claude(tier):
        return next(
            (m for m in tiers[tier]
             if models.get(m, {}).get("family") == "claude" and models[m]["endpoint"] == target_ep),
            None,
        )

    slots = {}
    for slot, tier in (("opus", "tier1"), ("sonnet", "tier2"), ("haiku", "tier3")):
        explicit_slot = spec.get(slot)
        if explicit_slot:
            slots[slot] = explicit_slot
        else:
            slots[slot] = first_claude(tier) if target_ep else None

    main = explicit_main
    if not main and target_ep:
        default = cat.get("default")
        if default in models and models[default]["family"] == "claude" and models[default]["endpoint"] == target_ep:
            main = default
        else:
            main = (
                slots["opus"]
                or slots["sonnet"]
                or slots["haiku"]
                or next((m for m, info in models.items() if info["family"] == "claude" and info["endpoint"] == target_ep), None)
            )

    ep_auth = endpoints[target_ep]["auth"] if target_ep in endpoints else "bearer"
    if cat["tools"]["claude_code"] and target_ep in endpoints and main and ep_auth == "api-key":
        problems.append(
            f"claude_code: endpoint '{target_ep}' uses auth 'api-key', which Claude Code cannot send without "
            "storing the key in a file; pick another endpoint (claude_code.endpoint) or set tools.claude_code: false"
        )

    default_key_env = None if ep_auth == "none" else ("ANTHROPIC_API_KEY" if ep_auth == "x-api-key" else "ANTHROPIC_AUTH_TOKEN")
    return {
        "model": main,
        **slots,
        "endpoint": target_ep,
        "key_env": spec.get("key_env") or default_key_env,
    }


def load_catalog(path: Path) -> dict:
    if not path.exists():
        raise CatalogError([f"{path} not found - copy catalog.example.yaml to catalog.yaml and fill it in"])
    return normalize_catalog(yaml.safe_load(path.read_text(encoding="utf-8")))


