class CatalogError(Exception):
    def __init__(self, problems: list[str]):
        super().__init__("\n".join(problems))
        self.problems = problems


def guess_family(model_id: str) -> str:
    name = model_id.lower()
    if "claude" in name:
        return "claude"
    if "gemini" in name:
        return "gemini"
    if re.search(r"gpt|codex|(^|[/-])o[134]([-/]|$)", name):
        return "gpt"
    return "open"


def normalize_catalog(raw: dict) -> dict:
    """Fill defaults and validate. Raises CatalogError listing every problem found."""
    raw = raw or {}
    problems: list[str] = []
    cat: dict = {}

    endpoints = {}
    for name, ep in (raw.get("endpoints") or {}).items():
        ep = ep or {}
        if not NAME_RE.match(str(name)):
            problems.append(f"endpoints.{name}: name may only use letters, digits, '-' and '_'")
        url = endpoint_root(ep.get("base_url"))
        if not url.startswith(("http://", "https://")):
            problems.append(f"endpoints.{name}.base_url: must start with http:// or https://")
        if not ep.get("key_env"):
            problems.append(f"endpoints.{name}.key_env: name of the environment variable holding the API key is required")
        endpoints[str(name)] = {"root": url, "key_env": ep.get("key_env")}
    if not endpoints:
        problems.append("endpoints: at least one endpoint is required")
    cat["endpoints"] = endpoints

    models = {}
    for mid, m in (raw.get("models") or {}).items():
        m = m or {}
        mid = str(mid)
        endpoint = m.get("endpoint") or (next(iter(endpoints)) if len(endpoints) == 1 else None)
        if endpoint not in endpoints:
            problems.append(f"models.{mid}.endpoint: '{endpoint}' is not a defined endpoint")
        context = m.get("context")
        if not isinstance(context, int) or isinstance(context, bool) or context <= 0:
            problems.append(f"models.{mid}.context: context window in tokens is required")
            context = 0
        models[mid] = {
            "endpoint": endpoint,
            "family": m.get("family") or guess_family(mid),
            "context": context,
            "max_output": int(m.get("max_output") or 8192),
            "reasoning": bool(m.get("reasoning", False)),
            "tools": bool(m.get("tools", True)),
            "vision": bool(m.get("vision", False)),
        }
    if not models:
        problems.append("models: at least one model is required")
    cat["models"] = models

    tiers = {}
    for tier in TIERS:
        ids = [str(x) for x in ((raw.get("tiers") or {}).get(tier) or [])]
        if not ids:
            problems.append(f"tiers.{tier}: needs at least one model")
        for mid in ids:
            if mid not in models:
                problems.append(f"tiers.{tier}: '{mid}' is not in models")
        tiers[tier] = ids
    cat["tiers"] = tiers

    default = raw.get("default") or (tiers["tier2"][0] if tiers["tier2"] else None)
    if default not in models:
        problems.append(f"default: '{default}' is not in models")
    cat["default"] = default

    policy = dict(raw.get("policy") or {})
    approvals = policy.get("approvals", "off")
    if isinstance(approvals, bool):  # YAML reads a bare off/on as a boolean
        approvals = "ask" if approvals else "off"
    if approvals not in ("off", "ask"):
        problems.append("policy.approvals: must be 'off' or 'ask'")
    cat["policy"] = {
        "telemetry": bool(policy.get("telemetry", False)),
        "auto_update": bool(policy.get("auto_update", False)),
        "external_web": bool(policy.get("external_web", True)),
        "approvals": approvals,
    }

    tools = raw.get("tools") or {}
    cat["tools"] = {t: bool(tools.get(t, True)) for t in ("opencode", "omo", "hermes", "claude_code")}

    roles = {}
    user_roles = raw.get("omo_roles") or {}
    for group in ("agents", "categories"):
        merged = {**DEFAULT_OMO_ROLES[group], **(user_roles.get(group) or {})}
        roles[group] = {}
        for role, spec in merged.items():
            spec = {"tier": spec} if isinstance(spec, str) else dict(spec or {})
            if spec.get("tier") not in TIERS:
                problems.append(f"omo_roles.{group}.{role}: tier must be one of {', '.join(TIERS)}")
                continue
            spec.setdefault("reasoning", TIER_REASONING[spec["tier"]])
            roles[group][role] = spec
    roles["concurrency"] = int(user_roles.get("concurrency") or 4)
    cat["omo_roles"] = roles

    mcp = {}
    for name, server in (raw.get("mcp") or {}).items():
        server = server or {}
        if not NAME_RE.match(str(name)):
            problems.append(f"mcp.{name}: name may only use letters, digits, '-' and '_'")
        if bool(server.get("command")) == bool(server.get("url")):
            problems.append(f"mcp.{name}: set exactly one of 'command' or 'url'")
        mcp[str(name)] = {
            "command": server.get("command"),
            "args": [str(a) for a in (server.get("args") or [])],
            "env": {str(k): str(v) for k, v in (server.get("env") or {}).items()},
            "url": server.get("url"),
            "headers": {str(k): str(v) for k, v in (server.get("headers") or {}).items()},
        }
    cat["mcp"] = mcp

    cat["claude_code"] = _resolve_claude_code(raw.get("claude_code") or {}, cat, problems)

    if cat["tools"]["hermes"] and default in models and 0 < models[default]["context"] < HERMES_MIN_CONTEXT:
        problems.append(
            f"default: hermes rejects models under {HERMES_MIN_CONTEXT} tokens of context "
            f"('{default}' has {models[default]['context']}); pick another default or set tools.hermes: false"
        )

    extra = raw.get("extra") or {}
    cat["extra"] = {t: dict(extra.get(t) or {}) for t in cat["tools"]}

    if problems:
        raise CatalogError(problems)
    return cat


def _resolve_claude_code(spec: dict, cat: dict, problems: list[str]) -> dict:
    """Pick Claude-family models for the main/opus/sonnet/haiku slots (Claude Code supports only Claude models).

    Claude Code talks to a single ANTHROPIC_BASE_URL, so slots left unset are filled only from the endpoint of
    the main model; mixing endpoints is an error only when the catalog names the models explicitly.
    """
    models, tiers = cat["models"], cat["tiers"]

    def is_claude(mid):
        return models.get(mid, {}).get("family") == "claude"

    # which endpoint Claude Code points at: an explicit choice, else the default model, else tier order
    explicit = [spec.get(s) for s in ("model", "opus", "sonnet", "haiku") if spec.get(s)]
    candidates = explicit + [cat.get("default")] + [m for t in TIERS for m in tiers[t]] + list(models)
    endpoint = next((models[m]["endpoint"] for m in candidates if is_claude(m)), None)

    def pick(tier_order):
        ordered = [m for t in tier_order for m in tiers[t]] + list(models)
        return next((m for m in ordered if is_claude(m) and models[m]["endpoint"] == endpoint), None)

    slots = {
        "opus": spec.get("opus") or pick(("tier1", "tier2", "tier3")),
        "sonnet": spec.get("sonnet") or pick(("tier2", "tier1", "tier3")),
        "haiku": spec.get("haiku") or pick(("tier3", "tier2", "tier1")),
    }
    main = spec.get("model")
    if not main:
        default = cat.get("default")
        main = default if is_claude(default) and models[default]["endpoint"] == endpoint else (
            slots["opus"] or slots["sonnet"] or slots["haiku"])
    chosen = {"model": main, **slots}
    for slot, mid in chosen.items():
        if mid is None:
            continue
        if mid not in models:
            problems.append(f"claude_code.{slot}: '{mid}' is not in models")
        elif models[mid]["family"] != "claude":
            problems.append(f"claude_code.{slot}: '{mid}' is not a Claude model; Claude Code supports only Claude models")
    used = {models[m]["endpoint"] for m in chosen.values() if m in models}
    if len(used) > 1:
        problems.append("claude_code: all Claude Code models must be on the same endpoint")
    chosen["endpoint"] = next(iter(used), None)
    endpoint_key = cat["endpoints"].get(chosen["endpoint"], {}).get("key_env")
    chosen["key_env"] = spec.get("key_env") or endpoint_key or "ANTHROPIC_AUTH_TOKEN"
    return chosen


def load_catalog(path: Path) -> dict:
    if not path.exists():
        raise CatalogError([f"{path} not found - copy catalog.example.yaml to catalog.yaml and fill it in"])
    return normalize_catalog(yaml.safe_load(path.read_text(encoding="utf-8")))


