@dataclass
class FileOp:
    rel: str                 # path under out/
    target: Path             # where it is installed
    kind: str                # json | jsonc | merge_json | merge_yaml | block | text | copy
    data: object = None
    replace: tuple = ()
    union: tuple = ()
    source: Path | None = None

    def fragment(self) -> bytes:
        """What is written to out/ for review (the patch, for merged files)."""
        if self.kind == "copy":
            return self.source.read_bytes()
        if self.kind in ("json", "merge_json"):
            return dump_json(self.data).encode()
        if self.kind == "jsonc":
            return (f"// {GENERATED_NOTE}\n" + dump_json(self.data)).encode()
        if self.kind == "merge_yaml":
            return yaml.safe_dump(self.data, sort_keys=False, allow_unicode=True).encode()
        return str(self.data).encode()

    def final(self) -> bytes:
        """Content the target will have after apply (merges read the existing target)."""
        if self.kind == "merge_json":
            existing = {}
            if self.target.exists():
                existing = json.loads(strip_jsonc(self.target.read_text(encoding="utf-8")) or "{}")
            return dump_json(deep_merge(existing, self.data, self.replace, self.union)).encode()
        if self.kind == "merge_yaml":
            existing = {}
            if self.target.exists():
                existing = yaml.safe_load(self.target.read_text(encoding="utf-8")) or {}
            merged = deep_merge(existing, self.data, self.replace, self.union)
            return yaml.safe_dump(merged, sort_keys=False, allow_unicode=True).encode()
        if self.kind == "block":
            existing = self.target.read_text(encoding="utf-8") if self.target.exists() else ""
            return replace_block(existing, str(self.data)).encode()
        return self.fragment()


def tool_dirs(home: Path | None) -> dict:
    explicit = home is not None
    h = Path(home) if explicit else Path.home()
    if explicit:
        hermes = h / "AppData" / "Local" / "hermes" if os.name == "nt" else h / ".hermes"
    elif os.environ.get("HERMES_HOME"):
        hermes = Path(os.environ["HERMES_HOME"])
    elif os.name == "nt" and os.environ.get("LOCALAPPDATA"):
        hermes = Path(os.environ["LOCALAPPDATA"]) / "hermes"
    else:
        hermes = h / ".hermes"
    return {"home": h, "opencode": h / ".config" / "opencode", "omo": h / ".omo",
            "hermes": hermes, "claude": h / ".claude"}


def _hermes_removal_notes(target: Path, patch: dict) -> list[str]:
    if not target.exists():
        return []
    try:
        existing = yaml.safe_load(target.read_text(encoding="utf-8")) or {}
    except Exception:
        return []
    if not isinstance(existing, dict):
        return []
    notes = []
    new_providers = set((patch.get("providers") or {}).keys())
    old_providers = existing.get("providers")
    if isinstance(old_providers, dict):
        for name in old_providers:
            if str(name) not in new_providers:
                notes.append(f"hermes: removed provider '{name}' not in catalog")
    old_cp = existing.get("custom_providers")
    if isinstance(old_cp, list) and "custom_providers" not in patch:
        for entry in old_cp:
            if isinstance(entry, dict):
                label = str(entry.get("name") or entry.get("base_url") or "").strip()
                if label and label not in new_providers:
                    notes.append(f"hermes: removed legacy custom_providers entry '{label}' not in catalog")

    def _fb_names(raw) -> list[str]:
        items = [raw] if isinstance(raw, dict) else raw if isinstance(raw, list) else []
        out = []
        for item in items:
            if isinstance(item, dict) and item.get("provider") and item.get("model"):
                out.append(f"{str(item['provider']).strip()}/{str(item['model']).strip()}")
        return out

    kept_fb = set(_fb_names(patch.get("fallback_providers")) + _fb_names(patch.get("fallback_model")))
    seen_dropped = set()
    for key in ("fallback_providers", "fallback_model"):
        for label in _fb_names(existing.get(key)):
            if label not in kept_fb and label not in seen_dropped:
                seen_dropped.add(label)
                notes.append(f"hermes: dropped fallback entry '{label}'")
    return notes


