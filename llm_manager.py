def assist_config(raw: dict) -> tuple[dict | None, list[str]]:
    """The catalog's optional assist: block (an OpenAI-compatible chat completions API with Bearer auth).

    Returns ({"root", "key_env", "model"}, []) when usable, (None, problems) when broken, (None, []) when absent."""
    block = (raw or {}).get("assist")
    if block is None:
        return None, []
    if not isinstance(block, dict):
        return None, ["assist: must be a mapping with base_url, key_env and model"]
    problems = []
    root = endpoint_root(block.get("base_url"))
    if not root.startswith(("http://", "https://")):
        problems.append("assist.base_url: must start with http:// or https://")
    for field_name, text in (("key_env", "name of the environment variable holding the assist API key"),
                             ("model", "model the assist API should use")):
        if not isinstance(block.get(field_name), str) or not block[field_name].strip():
            problems.append(f"assist.{field_name}: {text} is required")
    if problems:
        return None, problems
    return {"root": root, "key_env": block["key_env"].strip(), "model": block["model"].strip()}, []


def ask_api(cfg: dict, evidence: dict, timeout: int = ASSIST_TIMEOUT_API) -> tuple[object | None, str]:
    """Ask the configured assist API (OpenAI chat completions, Bearer). Returns (message content, "") or
    (None, reason)."""
    key = os.environ.get(cfg["key_env"])
    if not key:
        return None, f"environment variable {cfg['key_env']} (assist API key) is not set"
    body = {"model": cfg["model"], "temperature": 0,
            "messages": [{"role": "system", "content": ASSIST_PROMPT},
                         {"role": "user", "content": json.dumps(evidence, ensure_ascii=False)}]}
    status, answer, _ = http_call(cfg["root"] + "/v1/chat/completions", key, body, timeout=timeout)
    if status is None:
        return None, f"assist API {cfg['root']} is unreachable: {redact_body(str(answer), key, 200)}"
    if status != 200:
        text = answer if isinstance(answer, str) else json.dumps(answer)
        return None, f"assist API answered HTTP {status}: {redact_body(text, key, 200)}"
    try:
        content = answer["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError):
        content = None
    if isinstance(content, list):  # content parts
        content = "".join(p["text"] for p in content
                          if isinstance(p, dict) and isinstance(p.get("text"), str)) or None
    if not isinstance(content, (str, dict)) or not content:
        return None, "assist API answer has no message content"
    return content, ""


def claude_gateway_url(claude_dir: Path) -> str | None:
    """The gateway Claude Code talks to (ANTHROPIC_BASE_URL from the environment, else from its settings.json)."""
    url = os.environ.get("ANTHROPIC_BASE_URL", "").strip()
    if url:
        return url
    try:
        settings = json.loads((Path(claude_dir) / "settings.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    env = settings.get("env") if isinstance(settings, dict) else None
    url = env.get("ANTHROPIC_BASE_URL") if isinstance(env, dict) else None
    return url.strip() if isinstance(url, str) and url.strip() else None


def ask_claude(evidence: dict, timeout: int = ASSIST_TIMEOUT_CLAUDE) -> tuple[object | None, str]:
    """Ask the installed Claude Code (claude -p, no saved session). Returns (answer, "") or (None, reason).

    The evidence holds raw gateway bodies, so the judge gets nothing it could act with: no built-in tools
    (--tools ""), no MCP servers (--strict-mcp-config without --mcp-config), only the user's own settings
    (--setting-sources user keeps their gateway env and auth but skips project and local settings and their
    hooks), and an empty temporary working directory so no project CLAUDE.md or settings are picked up."""
    cmd = ["claude", "-p", "--output-format", "json", "--tools", "", "--strict-mcp-config",
           "--setting-sources", "user", "--no-session-persistence", "--json-schema", json.dumps(ASSIST_SCHEMA)]
    stdin = ASSIST_PROMPT + "\n" + json.dumps(evidence, ensure_ascii=False, indent=1)
    with tempfile.TemporaryDirectory(prefix="llm-manager-assist-") as neutral:
        code, out = run(cmd, timeout, input=stdin, cwd=neutral)
    if code is None:
        return None, f"claude: {out}"
    if code != 0:
        return None, f"claude exited with code {code}: {out[-300:]}"
    try:
        data = json.loads(out)
    except ValueError:
        data = _first_json_object(out)
    if not isinstance(data, dict):
        return None, "claude printed no JSON result"
    if data.get("is_error"):
        return None, f"claude reported an error: {str(data.get('result') or data.get('subtype') or '')[:300]}"
    payload = data.get("structured_output")
    if payload is None:
        payload = data.get("result")
    if payload is None or payload == "":
        return None, "claude returned no answer"
    return payload, ""


def choose_judge(mode: str, raw: dict, claude_dir: Path) -> tuple[str | None, object, list[str]]:
    """Pick who answers: the assist: API ("api") or Claude Code ("claude").

    Returns (name or None, callable evidence -> (payload, reason) or None, messages to print).
    auto: the assist: block when the catalog has one, else Claude Code only when it is on a gateway."""
    if mode not in ("auto", "api", "claude"):
        raise ValueError(f"unknown assist mode {mode!r}")
    cfg, problems = assist_config(raw)
    if mode == "claude":
        if claude_gateway_url(claude_dir):
            return "claude", ask_claude, ["assist: asking Claude Code (through its gateway)"]
        return "claude", ask_claude, ["warning: Claude Code is not on a gateway (ANTHROPIC_BASE_URL is not set), so "
                                      "the redacted probe evidence goes to Anthropic directly"]
    if cfg:
        return "api", lambda evidence: ask_api(cfg, evidence), [f"assist: asking {cfg['model']} at {cfg['root']}"]
    if problems or mode == "api":
        return None, None, ["assist: skipped - " + ("; ".join(problems) if problems else
                                                     "the catalog has no assist: block (base_url, key_env, model)")]
    if claude_gateway_url(claude_dir):
        return "claude", ask_claude, ["assist: asking Claude Code (through its gateway)"]
    return None, None, ["assist: skipped - the catalog has no assist: block and Claude Code is not on a gateway "
                        "(ANTHROPIC_BASE_URL is not set); add an assist: block, or pass --assist claude to send the "
                        "redacted evidence to Anthropic"]


def detect_server(url: str, key: str | None, timeout: int = 10) -> dict:
    """Work out what kind of LLM server sits at url, which auth header it takes and where its API lives."""
    root = endpoint_root(url)
    res = {"root": root, "kind": None, "auth": None, "api_base": None,
           "evidence": [], "warnings": [], "renderable": False, "model_ids": [],
           "probes": [], "openapi": None}

    def probe(path: str, auth: str):
        """One GET, recorded in res["probes"] (key redacted, credential headers left out)."""
        status, body, headers = http_call(root + path, key, timeout=timeout, auth=auth)
        text = body if isinstance(body, str) else json.dumps(body)
        res["probes"].append({"method": "GET", "path": path, "auth": auth, "status": status,
                              "headers": {k: redact(str(v), key) for k, v in headers.items()
                                          if k not in SECRET_HEADERS},
                              "body": redact_body(text, key)})
        return status, body, headers
    host_kind = kind_from_host(root)
    if host_kind:
        res["evidence"].append(f"host name looks like {host_kind}")
    if host_kind in CLOUD_SIGNED:
        res["kind"] = host_kind
        res["warnings"].append(f"{host_kind} needs {CLOUD_SIGNED[host_kind]} request signing, which these tools cannot "
                               "do with a plain key; put an OpenAI-compatible gateway such as LiteLLM in front of it")
        return res

    seen_headers: dict = {}
    rejected = set()
    found = None
    for base in MODEL_LIST_BASES:
        for auth in (AUTH_STYLES if key else ("none",)):
            status, body, headers = probe(base + "/models", auth)
            if status is None:
                res["kind"] = "unreachable"
                res["evidence"].append(f"{root}: {body}")
                return res
            seen_headers.update(headers)
            if status in (401, 403):
                rejected.add(status)
            if status == 200 and isinstance(body, dict) and isinstance(body.get("data"), list):
                found = (auth, base, [str(m.get("id")) for m in body["data"] if isinstance(m, dict) and m.get("id")])
                break
        if found:
            break
    if found:
        res["auth"], res["api_base"], res["model_ids"] = found
        res["evidence"].append(f"{found[1]}/models lists {len(found[2])} models with {AUTH_LABELS[found[0]]}")

    probe_auth = res["auth"] or ("bearer" if key else "none")
    fingerprints = {}
    for path, name, test in (("/model_group/info", "litellm", lambda b: isinstance(b.get("data"), list)),
                             ("/api/tags", "ollama", lambda b: isinstance(b.get("models"), list)),
                             ("/version", "vllm", lambda b: isinstance(b.get("version"), str))):
        status, body, headers = probe(path, probe_auth)
        seen_headers.update(headers)
        if status == 200 and isinstance(body, dict) and test(body):
            fingerprints[name] = f"{path} answers like {name}"
    status, body, headers = probe("/openapi.json", probe_auth)
    seen_headers.update(headers)
    if status == 200:
        res["openapi"] = openapi_summary(body)

    names = list(seen_headers)
    if any(h.startswith("x-litellm") for h in names):
        fingerprints.setdefault("litellm", "x-litellm-* response headers")
    if "apim-request-id" in names or "x-ms-region" in names:
        fingerprints["azure-openai"] = "Azure response headers (apim-request-id / x-ms-region)"
    if any(h.startswith("anthropic-") for h in names):
        fingerprints["anthropic"] = "anthropic-* response headers"
    if any(h.startswith("openai-") for h in names):
        fingerprints["openai"] = "openai-* response headers"
    if "kong" in seen_headers.get("via", "").lower() or any(h.startswith("x-kong") for h in names):
        res["evidence"].append("requests pass through a Kong API gateway")
    if "x-amzn-requestid" in names:
        res["evidence"].append("requests pass through AWS (x-amzn-requestid header)")
    res["evidence"] += list(fingerprints.values())

    by_auth = {"api-key": "azure-openai", "x-api-key": "anthropic"}.get(res["auth"])
    for kind in ("litellm", "ollama", "vllm", host_kind, "azure-openai", "anthropic", "openai", by_auth):
        if kind and (kind in fingerprints or kind in (host_kind, by_auth)):
            res["kind"] = kind
            break
    else:
        res["kind"] = "openai-compatible" if found else "unknown"

    if not found:
        if rejected and key:
            codes = "/".join(str(c) for c in sorted(rejected))
            res["warnings"].append(f"the key was rejected (HTTP {codes}) with every auth style tried "
                                   "(Authorization: Bearer, api-key, x-api-key) - check the key and its permissions")
        elif rejected:
            res["warnings"].append("the server wants a key - set the environment variable named in key_env")
        else:
            res["warnings"].append("no model list at /v1/models, /openai/v1/models or /models - "
                                   "check base_url or ask the gateway team for the API path")
    elif res["auth"] in ("bearer", "none") and res["api_base"] == "/v1":
        res["renderable"] = True
    elif res["auth"] in ("bearer", "none") and res["api_base"].endswith("/v1"):
        res["warnings"].append(f"the API lives under {root}{res['api_base']}; "
                               f"set base_url to {root}{res['api_base']} in catalog.yaml")
    else:
        res["warnings"].append(f"this server takes {AUTH_LABELS[res['auth']]} at {root}{res['api_base'] or '/'}, but the "
                               "configs llm_manager writes use Authorization: Bearer at <base_url>/v1, "
                               "so the tools will not connect to it yet")
    return res


def print_detection(name: str, det: dict) -> None:
    print(f"[{name}] {det['root']}")
    print(f"  server:  {det['kind']}")
    if det["auth"]:
        print(f"  auth:    {AUTH_LABELS[det['auth']]}")
        print(f"  api:     {det['root']}{det['api_base']}")
    for item in det["evidence"]:
        print(f"  seen:    {item}")
    for item in det["warnings"]:
        print(f"  warning: {item}")


def needs_assist(det: dict) -> bool:
    """Whether a judge could add anything: rules found no usable format. Unreachable and cloud-signed servers
    have nothing to learn from (no answers to read, or a signing scheme no candidate can express)."""
    if det.get("kind") in ("unreachable", *CLOUD_SIGNED):
        return False
    return det.get("kind") == "unknown" or not det.get("renderable")


def assist_endpoint(det: dict, key: str | None, judge) -> dict:
    """Ask the judge about one endpoint and verify each candidate it proposes with a real request.

    Returns {"judge_reason", "problems", "candidates"}; judge_reason is why the judge gave no answer ("" if it did).
    Never raises: a broken judge or answer is reported so the other endpoints are still processed."""
    result = {"judge_reason": "", "problems": [], "candidates": []}
    try:
        evidence = build_evidence(det, key)
        payload, reason = judge(evidence)
    except Exception as exc:  # noqa: BLE001 - one endpoint's judge failure must not stop the others
        result["judge_reason"] = redact(f"judge failed: {type(exc).__name__}: {exc}", key)[:300]
        return result
    if payload is None:
        result["judge_reason"] = redact(str(reason or "the judge gave no answer"), key)
        return result
    cands, problems = parse_candidates(payload)
    result["problems"] = [redact(p, key) for p in problems]
    result["candidates"] = [verify_candidate(det["root"], key, {**c, "reason": redact(c["reason"], key)})
                            for c in cands]
    return result


def _candidate_path(cand: dict) -> str:
    query = cand.get("query") or {}
    return (cand.get("api_base") or "/") + ("?" + urllib.parse.urlencode(query) if query else "")


def print_assist(name: str, result: dict) -> None:
    """One line per candidate, plus a catalog endpoint block for each verified one.

    result may also carry "root" and "key_env" (the endpoint's), used in that block."""
    if result.get("judge_reason"):
        print(f"  assist: no answer - {result['judge_reason']}")
    for problem in result.get("problems") or []:
        print(f"  assist: ignored part of the answer - {problem}")
    if not result.get("judge_reason") and not result.get("candidates"):
        print("  assist: the judge proposed no usable connection format")
    for c in result.get("candidates") or []:
        line = f"  assist: [{c['status']}] {c['api']}, {AUTH_LABELS[c['auth']]}, {_candidate_path(c)}"
        line += f" - {c['reason'] or 'no reason given'}"
        if c.get("detail"):
            line += f" ({c['detail']})"
        print(line)
        if c["status"] != "verified":
            continue
        block = {"base_url": (result.get("root") or "<base_url>") + c["api_base"],
                 "key_env": result.get("key_env") or "<KEY_ENV>", "api": c["api"], "auth": c["auth"]}
        if c.get("query"):
            block["query"] = dict(c["query"])
        if c.get("extra_headers"):
            block["headers"] = {h: "${" + header_env_name(h) + "}" for h in c["extra_headers"]}
        print("    suggested endpoint (catalog.yaml endpoints:):")
        text = yaml.safe_dump({name: block}, sort_keys=False, allow_unicode=True, default_flow_style=False)
        print("\n".join("      " + line for line in text.rstrip().splitlines()))


class _Assist:
    """Runs the judge for the endpoints that need it; the judge is chosen on first use, so nothing is printed
    and nothing is asked when every endpoint already works."""

    def __init__(self, mode: str | None, raw: dict | None, claude_dir: Path | None):
        self.mode, self.raw, self.claude_dir = mode, raw or {}, claude_dir
        self.chosen = False
        self.judge = None

    def __call__(self, name: str, det: dict, key: str | None, key_env: str | None) -> dict | None:
        if not self.mode or not needs_assist(det):
            return None
        if not self.chosen:
            self.chosen = True
            claude_dir = self.claude_dir if self.claude_dir is not None else tool_dirs(None)["claude"]
            _, self.judge, messages = choose_judge(self.mode, self.raw, claude_dir)
            for message in messages:
                print(message)
        if self.judge is None:
            return None
        result = {**assist_endpoint(det, key, self.judge), "root": det["root"], "key_env": key_env}
        print_assist(name, result)
        return result


def cmd_detect(targets: list[tuple[str, str, str | None]], assist_mode: str | None = None,
               raw: dict | None = None, claude_dir: Path | None = None) -> dict:
    """targets: (name, base_url, key_env). Prints what each server is; never prints a key.

    assist_mode (auto/api/claude) asks a judge about endpoints the rules could not settle (raw holds the
    catalog's assist: block); those results gain "assist"."""
    assist = _Assist(assist_mode, raw, claude_dir)
    results = {}
    for name, url, key_env in targets:
        key = os.environ.get(key_env or "")
        if key_env and not key:
            print(f"warning: environment variable {key_env} is not set; probing {name} without a key")
        results[name] = detect_server(url, key)
        print_detection(name, results[name])
        found = assist(name, results[name], key, key_env)
        if found is not None:
            results[name]["assist"] = found
    return results


def preflight(cat: dict) -> tuple[dict, list[str]]:
    """Probe every endpoint the catalog puts models on, before configs are built or installed.

    Returns (detections by endpoint, problems). A problem means the tools would not work against that endpoint.
    """
    used = {m["endpoint"] for m in cat["models"].values()}
    # opencode, omo and hermes speak OpenAI chat completions with Bearer auth at <base_url>/v1
    needs_openai = any(cat["tools"][t] for t in ("opencode", "omo", "hermes"))
    targets = [(n, ep) for n, ep in cat["endpoints"].items() if n in used]
    print(f"preflight: checking {len(targets)} endpoint(s)")
    results, problems = {}, []
    for name, ep in targets:
        key = os.environ.get(ep["key_env"])
        det = detect_server(ep["root"], key)
        results[name] = det
        print_detection(name, det)
        if det["kind"] == "unreachable":
            problems.append(f"{name}: {det['root']} is unreachable ({det['evidence'][-1]})")
        elif not det["auth"] and not key:
            problems.append(f"{name}: environment variable {ep['key_env']} is not set")
        elif not det["renderable"] and (needs_openai or not det["auth"]):
            problems.append(f"{name}: " + (det["warnings"][0] if det["warnings"]
                                           else "the generated configs cannot connect to this server"))
        else:
            absent = [m for m, i in cat["models"].items() if i["endpoint"] == name and m not in det["model_ids"]]
            if absent:
                problems.append(f"{name}: the gateway does not serve {', '.join(absent)}")
    print("preflight: ok" if not problems else f"preflight: {len(problems)} problem(s)")
    return results, problems


def models_yaml(endpoint: str, models: dict) -> str:
    block = {}
    for mid, info in sorted(models.items()):
        block[mid] = {
            "endpoint": endpoint,
            "family": guess_family(mid),
            "context": info.get("context"),
            "max_output": info.get("max_output") or 8192,
            "reasoning": bool(info.get("reasoning")),
            "tools": True if info.get("tools") is None else bool(info["tools"]),
            "vision": bool(info.get("vision")),
        }
    return yaml.safe_dump({"models": block}, sort_keys=False, allow_unicode=True)


def cmd_discover(raw: dict, out_file: Path, probe_model: str | None, assist_mode: str | None = None,
                 claude_dir: Path | None = None) -> dict:
    """assist_mode: as in cmd_detect; the judge's verified candidates are printed and saved under "assist"."""
    assist = _Assist(assist_mode, raw, claude_dir)
    results = {}
    for name, ep in (raw.get("endpoints") or {}).items():
        ep = ep or {}
        root = endpoint_root(ep.get("base_url"))
        key = os.environ.get(ep.get("key_env") or "")
        if not key:
            print(f"warning: environment variable {ep.get('key_env')} is not set; calling {name} without a key")
        det = detect_server(root, key)
        print_detection(name, det)
        found = assist(name, det, key, ep.get("key_env"))
        if det["kind"] in ("unreachable", *CLOUD_SIGNED):
            results[name] = {"root": root, "server": det}
            print(f"  skipped model discovery for {name}\n")
            continue
        res = discover_endpoint(root, key, probe_model, auth=det["auth"] or "bearer",
                                api_base="/v1" if det["api_base"] is None else det["api_base"])
        res["server"] = det
        if found is not None:
            res["assist"] = found
        results[name] = res
        for src, status in res["sources"].items():
            print(f"  {src}: {status}")
        for fmt, r in res["formats"].items():
            print(f"  {fmt}: {'supported' if r['ok'] else 'failed (' + str(r['status']) + ')'}  (probed with {res['probe_model']})")
        missing = [m for m, i in res["models"].items() if i.get("context") is None]
        print(f"  {len(res['models'])} chat models found" +
              (f"; {len(missing)} without a context size - fill 'context' in by hand" if missing else ""))
        print(models_yaml(name, res["models"]))
    out_file.write_text(dump_json(results), encoding="utf-8")
    print(f"saved {out_file}; paste the models block into catalog.yaml, then assign tiers")
    return results


def cmd_verify(cat: dict) -> int:
    failures = 0

    def report(ok, label, detail=""):
        nonlocal failures
        failures += 0 if ok else 1
        print(f"[{'ok' if ok else 'FAIL'}] {label}" + (f" - {detail}" if detail else ""))

    commands = {"opencode": "opencode", "omo": "omo", "hermes": "hermes", "claude_code": "claude"}
    for tool, exe in commands.items():
        if not cat["tools"][tool]:
            continue
        code, out = run([exe, "--version"])
        report(code == 0, f"{exe} installed", out.splitlines()[0] if out else "")
    detections, problems = preflight(cat)
    for name, det in detections.items():
        mine = [p.split(": ", 1)[1] for p in problems if p.startswith(name + ": ")]
        report(not mine, f"{name} gateway ({det['kind']})", "; ".join(mine))
    cc = cat["claude_code"]
    if cat["tools"]["claude_code"] and cc["model"]:
        report(bool(os.environ.get(cc["key_env"])), f"environment variable {cc['key_env']} is set (Claude Code)")
    if cat["tools"]["omo"]:
        code, out = run(["omo", "doctor"], timeout=120)
        report(code == 0, "omo doctor", "" if code == 0 else out[-300:])
    if cat["tools"]["hermes"]:
        code, out = run(["hermes", "config", "check"], timeout=120)
        report(code == 0, "hermes config check", "" if code == 0 else out[-300:])
    if cat["tools"]["opencode"]:
        print("opencode reads keys from its background service - confirm with: opencode service status")
    print("all checks passed" if not failures else f"{failures} check(s) failed")
    return failures


def add_assist_flag(p: argparse.ArgumentParser) -> None:
    p.add_argument("--assist", nargs="?", const="auto", choices=["auto", "api", "claude"],
                   help="ask an LLM about endpoints the rules cannot settle and verify its suggestions: api = the "
                        "catalog's assist: block, claude = the installed Claude Code, auto (default) = assist: if "
                        "present, else Claude Code when it is on a gateway")


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--catalog", type=Path, default=ROOT / "catalog.yaml")
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("discover", help="query the gateway for models and supported API formats")
    p.add_argument("--probe-model", help="model used to test the API formats (default: first model found)")
    add_assist_flag(p)
    for name, text in (("build", "render configs into out/ for review"),
                       ("diff", "show what apply would change"),
                       ("apply", "back up and install the configs")):
        p = sub.add_parser(name, help=text)
        p.add_argument("--home", type=Path, help="install under this folder instead of your home (for testing)")
        p.add_argument("--skip-check", action="store_true",
                       help="do not probe the gateways first (offline use; apply then installs without checking)")
        if name == "apply":
            p.add_argument("--env", action="store_true",
                           help="also set non-secret environment variables and register Claude Code MCP servers")
    p = sub.add_parser("detect", help="identify each gateway's server type, auth header and API path")
    p.add_argument("--url", help="probe this address instead of the catalog endpoints (no catalog needed)")
    p.add_argument("--key-env", help="with --url: name of the environment variable holding the key")
    add_assist_flag(p)
    sub.add_parser("verify", help="check tools, keys and the gateway")
    args = parser.parse_args(argv)

    try:
        if args.command == "discover":
            if not args.catalog.exists():
                raise CatalogError([f"{args.catalog} not found - copy catalog.example.yaml to catalog.yaml first"])
            raw = yaml.safe_load(args.catalog.read_text(encoding="utf-8")) or {}
            cmd_discover(raw, ROOT / "discovered.json", args.probe_model, args.assist, tool_dirs(None)["claude"])
            return 0
        if args.command == "detect":
            raw = {}
            if args.url:
                targets = [("url", args.url, args.key_env)]
                if args.assist and args.catalog.exists():  # only for its assist: block
                    raw = yaml.safe_load(args.catalog.read_text(encoding="utf-8")) or {}
            else:
                if not args.catalog.exists():
                    raise CatalogError([f"{args.catalog} not found - copy catalog.example.yaml to catalog.yaml "
                                        "first, or pass --url"])
                raw = yaml.safe_load(args.catalog.read_text(encoding="utf-8")) or {}
                targets = [(n, (ep or {}).get("base_url"), (ep or {}).get("key_env"))
                           for n, ep in (raw.get("endpoints") or {}).items()]
            found = cmd_detect(targets, args.assist, raw, tool_dirs(None)["claude"] if args.assist else None)
            return 1 if any(d["kind"] in ("unreachable", "unknown") for d in found.values()) else 0
        cat = load_catalog(args.catalog)
        if args.command in ("build", "diff", "apply") and not args.skip_check:
            _, problems = preflight(cat)
            if problems and args.command == "apply":
                print("preflight failed - nothing was installed:", file=sys.stderr)
                for problem in problems:
                    print("  -", problem, file=sys.stderr)
                print("fix these, or re-run with --skip-check to install anyway", file=sys.stderr)
                return 3
            if problems:
                print("preflight: apply will refuse to install until these are fixed: " + "; ".join(problems))
            print()
        if args.command == "build":
            cmd_build(cat, args.home, ROOT / "out")
        elif args.command == "diff":
            cmd_diff(cat, args.home)
        elif args.command == "apply":
            cmd_apply(cat, args.home, ROOT / "backups", args.env)
        elif args.command == "verify":
            return 1 if cmd_verify(cat) else 0
    except CatalogError as exc:
        print("catalog problems:", file=sys.stderr)
        for problem in exc.problems:
            print("  -", problem, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
